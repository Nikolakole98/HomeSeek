-- HomeSeek: tabele, pravila pristupa (RLS) i skladiste slika.

create table public.profiles (
  id uuid primary key references auth.users (id) on delete cascade,
  email text not null,
  type text not null default 'korisnik' check (type in ('korisnik', 'agencija')),
  name text not null,
  phone text,
  pib text check (pib ~ '^[0-9]{9}$'),
  is_admin boolean not null default false,
  created_at timestamptz not null default now()
);

create table public.listings (
  id bigint generated by default as identity primary key,
  owner_id uuid references public.profiles (id) on delete cascade,
  deal text not null check (deal in ('Kupovina', 'Iznajmljivanje')),
  type text not null check (type in ('Stan', 'Kuća')),
  title text not null check (char_length(title) between 1 and 80),
  location text not null,
  address text,
  lat double precision,
  lon double precision,
  price integer not null check (price > 0),
  area integer not null check (area > 0),
  rooms integer not null check (rooms between 1 and 50),
  description text not null,
  details jsonb not null default '{}',
  photos jsonb not null default '[]',
  owner_name text,
  owner_phone text,
  owner_email text,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);

create table public.favorites (
  user_id uuid not null references public.profiles (id) on delete cascade,
  listing_id bigint not null references public.listings (id) on delete cascade,
  created_at timestamptz not null default now(),
  primary key (user_id, listing_id)
);

create index listings_owner_id_idx on public.listings (owner_id);
create index favorites_listing_id_idx on public.favorites (listing_id);

-- Profil se pravi na serveru. is_admin se namerno ne cita iz podataka sa registracije.
create function public.handle_new_user()
returns trigger
language plpgsql
security definer
set search_path = ''
as $$
begin
  insert into public.profiles (id, email, type, name, phone, pib)
  values (
    new.id,
    new.email,
    coalesce(new.raw_user_meta_data ->> 'type', 'korisnik'),
    coalesce(nullif(new.raw_user_meta_data ->> 'name', ''), new.email),
    new.raw_user_meta_data ->> 'phone',
    nullif(new.raw_user_meta_data ->> 'pib', '')
  );
  return new;
end;
$$;

create trigger on_auth_user_created
  after insert on auth.users
  for each row execute function public.handle_new_user();

create function public.touch_updated_at()
returns trigger
language plpgsql
set search_path = ''
as $$
begin
  new.updated_at = now();
  return new;
end;
$$;

create trigger listings_touch_updated_at
  before update on public.listings
  for each row execute function public.touch_updated_at();

create function public.is_admin()
returns boolean
language sql
stable
security definer
set search_path = ''
as $$
  select coalesce((select is_admin from public.profiles where id = auth.uid()), false);
$$;

-- Brisanje naloga trazi pristup auth semi, pa ide kroz ovu proveravanu funkciju.
create function public.admin_delete_user(target_id uuid)
returns void
language plpgsql
security definer
set search_path = ''
as $$
begin
  if not public.is_admin() then
    raise exception 'Samo administrator moze da brise naloge.' using errcode = '42501';
  end if;
  if exists (select 1 from public.profiles where id = target_id and is_admin) then
    raise exception 'Administratorski nalog ne moze da se obrise.' using errcode = '42501';
  end if;
  delete from auth.users where id = target_id;
end;
$$;

revoke execute on function public.admin_delete_user(uuid) from public, anon;
grant execute on function public.admin_delete_user(uuid) to authenticated;

alter table public.profiles enable row level security;
alter table public.listings enable row level security;
alter table public.favorites enable row level security;

-- Profili: kontakt podaci nisu javni, a korisnik sme da menja samo ime i telefon.
revoke insert, update, delete on public.profiles from anon, authenticated;
grant update (name, phone) on public.profiles to authenticated;

create policy "Profil vidi vlasnik ili administrator" on public.profiles
  for select to authenticated
  using (id = auth.uid() or public.is_admin());

create policy "Vlasnik menja svoj profil" on public.profiles
  for update to authenticated
  using (id = auth.uid())
  with check (id = auth.uid());

-- Oglasi: svi citaju, vlasnik i administrator menjaju.
create policy "Oglase vide svi" on public.listings
  for select to anon, authenticated
  using (true);

create policy "Prijavljeni objavljuju svoje oglase" on public.listings
  for insert to authenticated
  with check (owner_id = auth.uid());

create policy "Oglas menja vlasnik ili administrator" on public.listings
  for update to authenticated
  using (owner_id = auth.uid() or public.is_admin())
  with check (owner_id = auth.uid() or public.is_admin());

create policy "Oglas brise vlasnik ili administrator" on public.listings
  for delete to authenticated
  using (owner_id = auth.uid() or public.is_admin());

-- Sacuvani oglasi: svako upravlja samo svojom listom.
revoke update on public.favorites from anon, authenticated;

create policy "Sacuvane oglase vidi vlasnik ili administrator" on public.favorites
  for select to authenticated
  using (user_id = auth.uid() or public.is_admin());

create policy "Korisnik cuva oglase za sebe" on public.favorites
  for insert to authenticated
  with check (user_id = auth.uid());

create policy "Korisnik uklanja svoje sacuvane oglase" on public.favorites
  for delete to authenticated
  using (user_id = auth.uid());

-- Slike: javne za citanje, a svaki korisnik pise samo u svoj folder.
insert into storage.buckets (id, name, public, file_size_limit, allowed_mime_types)
values ('listing-photos', 'listing-photos', true, 5242880, array['image/jpeg']);

create policy "Korisnik dodaje slike u svoj folder" on storage.objects
  for insert to authenticated
  with check (bucket_id = 'listing-photos' and (storage.foldername(name))[1] = auth.uid()::text);

create policy "Sliku brise vlasnik ili administrator" on storage.objects
  for delete to authenticated
  using (
    bucket_id = 'listing-photos'
    and ((storage.foldername(name))[1] = auth.uid()::text or public.is_admin())
  );
